"""Build assets/data.js for the project page (index.html).

Contents:
  digits      certified decimal expansions (from the b-files)
  cheb        low-precision Chebyshev coefficients of the fixed point f(t), t = |x|^z (for plotting g)
  superstable superstable parameters mu_n of x -> 1 - mu |x|^z (period 2^n), and mu_inf
  convergence correct digits of alpha vs number of collocation nodes (small n, mpmath),
              plus the production runs
usage: uv run python src/site_data.py
"""
import json
import os
import sys

import mpmath as mp

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import proto  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BFILES = {
    (k, z): f"{k}_degree{z}.txt" for k in ("alpha", "delta") for z in (2, 4, 6, 8)
}
# final-stage node counts of the production runs (main run, check run) and agreement digits
RUNS = {
    2: {"n": 6514, "n_check": 7034, "agree_alpha": 10068, "agree_delta": 10066, "indep_alpha": 3015, "indep_delta": 3015},
    4: {"n": 5358, "n_check": 5893, "agree_alpha": 5070, "agree_delta": 5067, "indep_alpha": 1515, "indep_delta": 1515},
    6: {"n": 6523, "n_check": 7175, "agree_alpha": 5070, "agree_delta": 5067, "indep_alpha": 1515, "indep_delta": 1514},
    8: {"n": 7707, "n_check": 8477, "agree_alpha": 5070, "agree_delta": 5068, "indep_alpha": 1514, "indep_delta": 1515},
}


def digits_string(fname):
    rows = [l.split() for l in open(os.path.join(ROOT, "digits", fname)) if l.strip()]
    off = int(rows[0][0])  # number of digits before the point
    ds = "".join(r[1] for r in rows)
    return ds[:off] + "." + ds[off:]


def orbit(mu, z, N):
    x, dx = mp.mpf(0), mp.mpf(0)
    for _ in range(N):
        ax = abs(x)
        dx = -(ax ** z) - mu * z * ax ** (z - 1) * mp.sign(x) * dx
        x = 1 - mu * ax ** z
    return x, dx


def superstable(mu, z, N):
    for _ in range(80):
        x, dx = orbit(mu, z, N)
        step = x / dx
        mu -= step
        if abs(step) < mp.mpf(10) ** (-30):
            break
    return mu


def superstable_seq(z, delta, nmax):
    mus = [mp.mpf(0), mp.mpf(1)]  # period 1 (mu=0) and period 2 (mu=1)
    grid = [1 + mp.mpf(k) / 400 for k in range(1, 400)]
    vals = [orbit(m, z, 4)[0] for m in grid]
    k = next(i for i in range(len(grid) - 1) if vals[i] * vals[i + 1] < 0)
    mus.append(superstable((grid[k] + grid[k + 1]) / 2, z, 4))
    for n in range(3, nmax + 1):
        gap = (mus[-1] - mus[-2]) / delta
        m = superstable(mus[-1] + gap, z, 2 ** n)
        assert abs(m - (mus[-1] + gap)) < gap / 2, (z, n)  # must be the next superstable point
        mus.append(m)
    # accumulation point: geometric tail with the known delta
    mu_inf = mus[-1] + (mus[-1] - mus[-2]) / (delta - 1)
    return [float(m) for m in mus], float(mu_inf), mu_inf


def main():
    mp.mp.dps = 40
    data = {"digits": {}, "runs": RUNS, "cheb": {}, "superstable": {}, "convergence": {}}
    for (k, z), f in BFILES.items():
        data["digits"][f"{k}{z}"] = digits_string(f)

    c = None
    for z in [2, 2.5, 3, 3.5, 4, 5, 6, 7, 8]:
        for n in [10, 20, 30]:
            c, _ = proto.solve_fixed_point(z, n, c)
        if z in (2, 4, 6, 8):
            cz, _ = proto.solve_fixed_point(z, 40, c)
            data["cheb"][str(int(z))] = [float(x) for x in cz]
            print("cheb", z, flush=True)

    for z in (2, 4, 6, 8):
        delta = mp.mpf(data["digits"][f"delta{z}"][:40])
        mus, mu_inf_f, mu_inf = superstable_seq(z, delta, 14)
        data["superstable"][str(z)] = {"mu": mus, "mu_inf": mp.nstr(mu_inf, 20)}
        print("superstable", z, mp.nstr(mu_inf, 16), flush=True)

    # convergence: correct digits of alpha vs n (fixed point only), compared with the certified digits
    for z in (2, 4, 6, 8):
        mp.mp.dps = 110
        true = mp.mpf(data["digits"][f"alpha{z}"][:200])
        c = None
        for zz in [2, 2.5, 3, 3.5, 4, 5, 6, 7, 8]:
            if zz > z:
                break
            for n in [10, 20]:
                c, _ = proto.solve_fixed_point(zz, n, c)
        pts = []
        for n in range(4, 61, 4):
            c, a = proto.solve_fixed_point(z, n, c)
            err = abs(a - true) / true
            pts.append([n, round(float(-mp.log10(err)), 2) if err > 0 else 100.0])
        data["convergence"][str(z)] = pts
        print("convergence", z, pts[-1], flush=True)
        mp.mp.dps = 40

    out = os.path.join(ROOT, "assets", "data.js")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w") as fh:
        fh.write("// generated by src/site_data.py\nwindow.FEIG = ")
        json.dump(data, fh, separators=(",", ":"))
        fh.write(";\n")
    print("wrote", out, os.path.getsize(out), "bytes")


if __name__ == "__main__":
    main()
